// Compresses images in public/images and generates blur placeholders.
//
//   node scripts/optimize-images.mjs
//
// - JPG/PNG files are resized (max 2000px wide), converted to WebP and the
//   original is removed. Remember to update references to the new .webp path.
// - Writes src/content/image-blur.ts with a tiny blurred preview per image,
//   used by next/image `placeholder="blur"`.

import { readdir, stat, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const IMAGES_DIR = path.join(ROOT, "public", "images");
const OUTPUT = path.join(ROOT, "src", "content", "image-blur.ts");
const MAX_WIDTH = 2000;
const QUALITY = 80;

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
  );
  return files.flat();
}

const kb = (bytes) => `${Math.round(bytes / 1024)} KB`;
const toPublicPath = (file) => "/" + path.relative(path.join(ROOT, "public"), file).split(path.sep).join("/");

// 1. Convert JPG/PNG to WebP
for (const file of await walk(IMAGES_DIR)) {
  if (!/\.(jpe?g|png)$/i.test(file)) continue;
  const target = file.replace(/\.(jpe?g|png)$/i, ".webp");
  const before = (await stat(file)).size;

  await sharp(file)
    .rotate()
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .webp({ quality: QUALITY })
    .toFile(target);

  const after = (await stat(target)).size;
  await unlink(file);
  console.log(`${toPublicPath(file)}  ${kb(before)} -> ${kb(after)}  (${toPublicPath(target)})`);
}

// 2. Blur placeholders
const blur = {};
for (const file of (await walk(IMAGES_DIR)).sort()) {
  if (!/\.webp$/i.test(file)) continue;
  const buffer = await sharp(file).resize(16).webp({ quality: 40 }).toBuffer();
  blur[toPublicPath(file)] = `data:image/webp;base64,${buffer.toString("base64")}`;
}

const source = `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
export const IMAGE_BLUR: Record<string, string> = ${JSON.stringify(blur, null, 2)};

/** Props for next/image that show a blurred preview while the image loads. */
export function blurProps(src: string) {
  const blurDataURL = IMAGE_BLUR[src];
  return blurDataURL ? ({ placeholder: "blur", blurDataURL } as const) : {};
}
`;
await writeFile(OUTPUT, source);
console.log(`\nWrote ${Object.keys(blur).length} placeholders to ${path.relative(ROOT, OUTPUT)}`);
